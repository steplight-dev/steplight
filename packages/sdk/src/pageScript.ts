import { readFileSync } from "node:fs";
import { collectPageScan } from "@steplight/core";
import { BINDING_NAME, installPageListeners, installScanning } from "./inject.js";

/**
 * Assemble the standalone page script (`spec/page-scan.js`) from the real implementations: the page
 * scan from core, the click / input / submit listeners (never-capture rules included) and the
 * load / late-injection / route-change scanning. Any language can inject the result with its browser
 * driver's "init script" and receive events through a binding named `__steplightEmit`.
 * Run `pnpm spec` to rewrite the committed file; a test fails when it is out of date.
 * @example const script = buildPageScanScript()
 */
export function buildPageScanScript(): string {
  return `/* Steplight page script - GENERATED by \`pnpm spec\` (scripts/generate-spec.mjs). Do not edit.
 *
 * Injected into every page by an SDK (Playwright add_init_script / addInitScript). It reports through
 * a binding named "__steplightEmit" called with one object per event:
 *   { type: "scan", reason: "load" | "rescan" | "spa", scan: { url, title, text, dom: { url, nodes } } }
 *   { type: "click" | "change", selector, text }
 *   { type: "submit", selector, text, method, action, body }
 * Password, card, OTP and similar fields are never read (spec/never-capture.json). The script never
 * throws into the page and makes no network request. Redaction happens in the SDK, before anything is stored.
 */
(() => {
  "use strict";
  const BINDING_NAME = ${JSON.stringify(BINDING_NAME)};
  const collectPageScan = ${collectPageScan.toString()};
  const installPageListeners = ${installPageListeners.toString()};
  const installScanning = ${installScanning.toString()};
  installPageListeners(BINDING_NAME);
  installScanning(BINDING_NAME, collectPageScan);
})();
`;
}

let cached: string | undefined;

/**
 * The page script shipped next to this module (a copy of `spec/page-scan.js` made at build time).
 * One file is the single source of truth for every SDK.
 */
export function pageScanScript(): string {
  if (cached === undefined) {
    try {
      cached = readFileSync(new URL("./page-scan.js", import.meta.url), "utf8");
    } catch {
      // Running from source in the repository (tests): the committed file itself.
      cached = readFileSync(new URL("../../../spec/page-scan.js", import.meta.url), "utf8");
    }
  }
  return cached;
}
